"""Merge the approved Q1-Q100 register with the work-package states into a traceability CSV and a status table.

    python tools/build_rev_x_traceability.py

Reads docs/rev_x/handoff/APPROVED_REQUIREMENTS_Q1_Q100.csv, docs/rev_x/handoff/IMPLEMENTATION_TRACEABILITY.csv and docs/rev_x/WPU_STATUS.json;
writes docs/rev_x/REQUIREMENTS_TRACEABILITY_REV_X.csv and docs/rev_x/WPU_STATUS.md. A design decision is APPROVED; the implementation state is separate, and a
question is only as complete as the least complete work package that carries it. Questions no work package maps to are listed as such, never marked done.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
H = ROOT / "docs" / "rev_x" / "handoff"
OUT = ROOT / "docs" / "rev_x"
# decisions no work package carries: state and the reason, stated explicitly
EXTRA = {
    "Q035": ("PARTIAL", "Baseline versioned symbol catalogue and tag profiles exist (symbol_catalog.py, tag_profiles.py). The Rev X library is defined in code, not as a user catalogue; per-catalogue licence records are not yet enforced."),
    "Q039": ("PARTIAL", "JSON/CSV/XLSX/GraphML and the AI package exist and never write to a host database. Purpose-specific HAZOP/LOPA/QRA/index adapters are NOT_STARTED."),
    "Q042": ("TESTED", "Typed pipeline: every stage returns a StageOutcome (WPU-01); stages are cancellable, idempotent and recorded."),
    "Q051": ("PARTIAL", "Text, tables, notes, title block, valves, actuators, instruments, five equipment shapes, ports, drawn connections and loops are extracted as proposals. Line numbers as structured records, nozzle schedules, fittings, flow beyond arrows and non-standard symbols are not complete."),
    "Q052": ("PARTIAL", "Analysis runs on the whole drawing without teaching or preselection (symbol library, tiles, OCR). Real-sheet recall is NOT measured; teach-by-example remains available for what the library misses."),
}
ORDER = ["NOT_STARTED", "IN_PROGRESS", "BLOCKED", "FAILED", "NOT_RUN", "PARTIAL", "IMPLEMENTED", "TESTED"]   # least to most complete


def main() -> int:
    status = {k: v for k, v in json.loads((OUT / "WPU_STATUS.json").read_text(encoding="utf-8")).items() if not k.startswith("_")}
    wpu_rows = list(csv.DictReader((H / "IMPLEMENTATION_TRACEABILITY.csv").open(encoding="utf-8")))
    q_to_wpu: dict[str, list[str]] = {}
    for r in wpu_rows:
        for q in [x.strip() for x in r["mapped_owner_questions"].split(",") if x.strip()]:
            q_to_wpu.setdefault(q, []).append(r["wp_id"])
    rows = []
    for q in csv.DictReader((H / "APPROVED_REQUIREMENTS_Q1_Q100.csv").open(encoding="utf-8")):
        num = int(q["question_id"][1:])
        wps = q_to_wpu.get(f"Q{num}", []) + q_to_wpu.get(q["question_id"], [])
        wps = sorted(set(wps))
        if wps:
            worst = min((status[w]["state"] for w in wps), key=ORDER.index)
            ev_mod = sorted({m for w in wps for m in status[w]["modules"]})
            ev_test = sorted({t for w in wps for t in status[w]["tests"]})
            note = " | ".join(f"{w}: {status[w]['notes']}" for w in wps)[:900]
        else:
            worst, note = EXTRA.get(q["question_id"], ("NOT_MAPPED_TO_WPU", "No work package carries this decision"))
            ev_mod, ev_test = [], []
        gate = "G-SW"
        if num in (20, 30, 48, 95, 96, 97, 98):
            gate = "G-EXT (accuracy: NOT_RUN)"
        if num in (17, 41, 47, 50, 100):
            gate = "G-HOST (NOT_RUN)"
        rows.append({"question_id": q["question_id"], "decision": f"APPROVED option {q['approved_option']}", "implementation_state": worst, "work_packages": ";".join(wps),
                     "gate": gate, "evidence_modules": ";".join(ev_mod), "evidence_tests": ";".join(ev_test), "requirement": q["normative_requirement"][:300], "notes": note})
    with (OUT / "REQUIREMENTS_TRACEABILITY_REV_X.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["implementation_state"]] = counts.get(r["implementation_state"], 0) + 1
    lines = ["# Rev X work-package status", "", "Generated by `tools/build_rev_x_traceability.py` from `WPU_STATUS.json`. **TESTED = automated tests on synthetic fixtures pass here; it is not accuracy, "
             "not real-sheet validation, not Windows acceptance, and not engineering review.**", "", "| WPU | Title | State | Modules | Notes |", "|---|---|---|---|---|"]
    for k, v in status.items():
        lines.append(f"| {k} | {v['title']} | **{v['state']}** | {', '.join('`'+m+'`' for m in v['modules'][:4])} | {v['notes']} |")
    lines += ["", "## Q1-Q100 by implementation state (least complete carrying work package)", ""] + [f"* {k}: {n}" for k, n in sorted(counts.items(), key=lambda kv: ORDER.index(kv[0]) if kv[0] in ORDER else -1)]
    (OUT / "WPU_STATUS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"questions": len(rows), "by_state": counts}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
