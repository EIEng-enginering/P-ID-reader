"""Generate the SYNTHETIC developer benchmark corpus with exact ground truth.

    python tools/make_benchmark_corpus.py OUT_DIR [--count 120] [--final-count 30] [--seed 20261107]

Writes ``drawing_###.pdf`` (vector, rotated, cropped or scanned variants) and a
``manifest.json`` holding, per drawing, the generated ground truth (tags with
class and box, valves, instruments, drawn-line paths) and the ``split``:

* ``dev``   - may be used freely while building the software;
* ``final`` - reserved untouched final test. The scorer refuses to read these
  without ``--run-final`` and appends every use to ``final_access.log``.

These drawings are generated by this repository's author. They are **not**
independent, not real plant drawings and prove nothing about industrial
accuracy; they exist to detect regressions and to exercise the scoring harness.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import random
from pathlib import Path

from reportlab.pdfgen import canvas

CLASS_PREFIX = {"VESSEL": "V", "PUMP": "P", "HEAT_EXCHANGER": "E", "TANK": "TK"}
PAGE_SIZES = [(842, 595), (1190, 842), (842, 595)]
VARIANTS = ("vector", "vector", "vector", "rot90", "rot180", "cropped", "scanned")


class Drawing:
    def __init__(self, rng: random.Random, number: int):
        self.rng = rng
        self.number = number
        self.w, self.h = rng.choice(PAGE_SIZES)
        self.variant = rng.choice(VARIANTS)
        self.truth = {"equipment": [], "instruments": [], "valves": [], "lines": [], "paths": []}
        self.used: set[int] = set()
        self.buf = io.BytesIO()
        self.c = canvas.Canvas(self.buf, pagesize=(self.w, self.h), pageCompression=0, invariant=1)

    def _num(self, base: int, span: int) -> int:
        while True:
            n = base + self.rng.randrange(span)
            if n not in self.used:
                self.used.add(n)
                return n

    def box(self, x0, y0, x1, y1) -> dict:  # reportlab bottom-left -> normalised top-left
        return {"x0": round(x0 / self.w, 5), "y0": round(1 - y1 / self.h, 5),
                "x1": round(x1 / self.w, 5), "y1": round(1 - y0 / self.h, 5)}

    def bowtie(self, x, y, a=14, b=10):
        c = self.c
        for dx, dy in ((-a, -b), (-a, b), (a, -b), (a, b)):
            c.line(x, y, x + dx, y + dy)
        c.line(x - a, y - b, x - a, y + b)
        c.line(x + a, y - b, x + a, y + b)

    def build(self):
        c, rng = self.c, self.rng
        c.setFont("Helvetica", 9)
        c.drawString(30, self.h - 24, f"SYNTHETIC BENCHMARK DRAWING {self.number:03d} - NOT A PLANT")
        c.rect(14, 14, self.w - 28, self.h - 28)
        rows = rng.choice([1, 2, 2, 3])
        row_gap = (self.h - 140) / rows
        for r in range(rows):
            y = self.h - 110 - r * row_gap - 40
            count = rng.randint(3, 5)
            step = (self.w - 120) / count
            xs = [60 + step * i + step / 2 for i in range(count)]
            items = []
            for x in xs:
                cls = rng.choice(list(CLASS_PREFIX))
                tag = f"{CLASS_PREFIX[cls]}-{self._num(100 + 100 * r, 90)}"
                if cls == "PUMP":
                    rad = 22
                    c.circle(x, y, rad)
                    c.drawCentredString(x, y - 3, tag)
                    left, right = x - rad, x + rad
                    box = self.box(x - rad, y - rad, x + rad, y + rad)
                else:
                    wd, ht = (64, 80) if cls in ("VESSEL", "TANK") else (70, 40)
                    c.rect(x - wd / 2, y - ht / 2, wd, ht)
                    c.drawCentredString(x, y - 3, tag)
                    left, right = x - wd / 2, x + wd / 2
                    box = self.box(x - wd / 2, y - ht / 2, x + wd / 2, y + ht / 2)
                top = y + (22 if cls == "PUMP" else (40 if cls in ("VESSEL", "TANK") else 20))
                items.append({"tag": tag, "class": cls, "x": x, "y": y, "left": left, "right": right,
                              "top": top, "box": box})
                self.truth["equipment"].append({"tag": tag, "class": cls, "page": 1, "bbox": box})
            for a, b in zip(items, items[1:]):
                x_start, x_end = a["right"], b["left"]
                nvalves = rng.choice([0, 1, 1, 2])
                span = x_end - x_start
                centres = [x_start + span * (k + 1) / (nvalves + 1) for k in range(nvalves)]
                cursor = x_start
                valve_tags = []
                for vx in centres:
                    c.line(cursor, a["y"], vx - 14, a["y"])
                    self.bowtie(vx, a["y"])
                    prefix = rng.choice(["XV", "HV", "CV"])
                    vtag = f"{prefix}-{self._num(200 + 100 * r, 90)}"
                    c.drawCentredString(vx, a["y"] + 20, vtag)
                    vcls = {"XV": "VALVE_ONOFF", "HV": "VALVE_MANUAL", "CV": "VALVE_CONTROL"}[prefix]
                    self.truth["valves"].append({"tag": vtag, "class": vcls, "page": 1,
                                                 "glyph_bbox": self.box(vx - 14, a["y"] - 10, vx + 14, a["y"] + 10),
                                                 "label_bbox": self.box(vx - 18, a["y"] + 18, vx + 18, a["y"] + 28)})
                    valve_tags.append(vtag)
                    cursor = vx + 14
                c.line(cursor, a["y"], x_end, a["y"])
                if span > 90:
                    ln = f'{rng.choice([2, 3, 4, 6])}"-P-{self._num(1500, 400)}-A1A'
                    c.drawCentredString((x_start + x_end) / 2, a["y"] - 26, ln)
                    self.truth["lines"].append({"tag": ln, "page": 1})
                self.truth["paths"].append({"a": a["tag"], "b": b["tag"], "valves": valve_tags})
            for it in items:
                if rng.random() < 0.55:
                    prefix = rng.choice(["PT", "LT", "TT", "FT"])
                    itag = f"{prefix}-{self._num(300 + 100 * r, 90)}"
                    cy, rad = it["top"] + 52, 18
                    c.circle(it["x"], cy, rad)
                    c.drawCentredString(it["x"], cy - 3, itag)
                    c.setDash(3, 2)
                    c.line(it["x"], it["top"], it["x"], cy - rad)
                    c.setDash()
                    self.truth["instruments"].append({
                        "tag": itag, "class": "INSTRUMENT", "page": 1, "attached_to": it["tag"],
                        "bbox": self.box(it["x"] - rad, cy - rad, it["x"] + rad, cy + rad)})
        c.drawString(30, 30, f"DWG: SYN-{self.number:03d}   REV: A")
        c.save()

    def finish(self) -> bytes:
        data = self.buf.getvalue()
        if self.variant == "vector":
            return data
        from pypdf import PdfReader, PdfWriter
        if self.variant in ("rot90", "rot180"):
            reader = PdfReader(io.BytesIO(data))
            writer = PdfWriter()
            page = reader.pages[0]
            page.rotate(90 if self.variant == "rot90" else 180)
            writer.add_page(page)
            out = io.BytesIO()
            writer.write(out)
            return out.getvalue()
        if self.variant == "cropped":
            reader = PdfReader(io.BytesIO(data))
            writer = PdfWriter()
            page = reader.pages[0]
            page.cropbox.lower_left = (10, 10)
            page.cropbox.upper_right = (self.w - 10, self.h - 10)
            writer.add_page(page)
            out = io.BytesIO()
            writer.write(out)
            return out.getvalue()
        # scanned: rasterise then wrap the picture in an image-only PDF (no text layer)
        import pypdfium2 as pdfium
        from reportlab.lib.utils import ImageReader
        image = pdfium.PdfDocument(data)[0].render(scale=2.2).to_pil().convert("L")
        out = io.BytesIO()
        c = canvas.Canvas(out, pagesize=(self.w, self.h), pageCompression=0, invariant=1)
        c.drawImage(ImageReader(image), 0, 0, self.w, self.h)
        c.save()
        return out.getvalue()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--count", type=int, default=120)
    ap.add_argument("--final-count", type=int, default=30)
    ap.add_argument("--seed", type=int, default=20261107)
    args = ap.parse_args(argv)
    if args.final_count >= args.count or args.final_count < 1:
        ap.error("final-count must be >=1 and smaller than count")
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    manifest = {"kind": "SYNTHETIC_DEVELOPER_BENCHMARK_NOT_INDEPENDENT", "seed": args.seed, "drawings": []}
    ids = list(range(1, args.count + 1))
    final = set(random.Random(args.seed ^ 0x5EED).sample(ids, args.final_count))
    for n in ids:
        d = Drawing(random.Random(f"{args.seed}-{n}"), n)
        d.build()
        data = d.finish()
        name = f"drawing_{n:03d}.pdf"
        (out / name).write_bytes(data)
        manifest["drawings"].append({"file": name, "sha256": hashlib.sha256(data).hexdigest(),
                                     "variant": d.variant, "split": "final" if n in final else "dev",
                                     "page_size_pt": [d.w, d.h], "truth": d.truth})
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1, sort_keys=True), encoding="utf-8")
    counts = {s: sum(1 for d in manifest["drawings"] if d["split"] == s) for s in ("dev", "final")}
    variants = {v: sum(1 for d in manifest["drawings"] if d["variant"] == v) for v in set(VARIANTS)}
    print(json.dumps({"written": len(ids), "splits": counts, "variants": variants}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
