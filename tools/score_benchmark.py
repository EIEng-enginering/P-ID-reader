"""Score the software against the SYNTHETIC developer benchmark (not independent).

    python tools/score_benchmark.py CORPUS_DIR REPORT.json [--split dev] [--limit N]
    python tools/score_benchmark.py CORPUS_DIR REPORT.json --split final --run-final

Metrics, each with explicit denominators:
  tags      - tag text found / missing / spurious vs ground-truth tags (equipment, instruments, valves)
  classes   - class of correctly found tags
  lines     - line-number text found
  valves    - valve glyph candidates whose centre falls inside a truth glyph box (one-to-one)
  paths     - drawn-line paths between equipment tag pairs proposed vs truth

The ``final`` split is reserved: it is read only with ``--run-final`` and each use
is appended to ``final_access.log`` next to the manifest. Results here come from
drawings generated by this repository's own generator; they are developer
regression numbers, never evidence of accuracy on industrial drawings.
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pid_reader.api import ReadParams  # noqa: E402
from pid_reader.engineering.pipeline import analyze_drawing  # noqa: E402
from pid_reader.engineering.connectivity import drawing_connectivity  # noqa: E402
from pid_reader.engineering.project import ProjectStore  # noqa: E402
from pid_reader.engineering.standalone_read import read_pid_standalone  # noqa: E402


def transform_box(box: dict, variant: str, size: tuple[int, int]) -> dict:
    x0, y0, x1, y1 = box["x0"], box["y0"], box["x1"], box["y1"]
    if variant == "rot180":
        return {"x0": 1 - x1, "y0": 1 - y1, "x1": 1 - x0, "y1": 1 - y0}
    if variant == "rot90":  # clockwise quarter turn
        return {"x0": 1 - y1, "y0": x0, "x1": 1 - y0, "y1": x1}
    if variant == "cropped":
        w, h = size
        f = lambda v, n: min(1.0, max(0.0, (v * n - 10) / (n - 20)))
        return {"x0": f(x0, w), "y0": f(y0, h), "x1": f(x1, w), "y1": f(y1, h)}
    return box


def centre_in(box: dict, outer: dict, pad: float = 0.004) -> bool:
    cx, cy = (box["x0"] + box["x1"]) / 2, (box["y0"] + box["y1"]) / 2
    return outer["x0"] - pad <= cx <= outer["x1"] + pad and outer["y0"] - pad <= cy <= outer["y1"] + pad


def prf(tp: int, fp: int, fn: int) -> dict:
    return {"tp": tp, "fp": fp, "fn": fn,
            "precision": round(tp / (tp + fp), 4) if tp + fp else None,
            "recall": round(tp / (tp + fn), 4) if tp + fn else None}


def score_drawing(entry: dict, pdf: bytes, ocr_engine: str | None) -> dict:
    truth = entry["truth"]
    variant = entry["variant"]
    size = tuple(entry["page_size_pt"])
    result = read_pid_standalone(pdf, ReadParams(), filename=entry["file"], ocr_engine=ocr_engine)
    tag_truth = {}
    for e in truth["equipment"] + truth["instruments"] + truth["valves"]:
        tag_truth[e["tag"]] = e["class"]
    pred = {}
    for o in result["objects"]:
        if o["class"] not in ("LINE", "NOTE") and o["text"]:
            pred.setdefault(o["text"], o["class"])
    found = set(tag_truth) & set(pred)
    out = {"file": entry["file"], "variant": variant, "split": entry["split"],
           "tags": prf(len(found), len(set(pred) - set(tag_truth)), len(set(tag_truth) - set(pred))),
           "class_correct": sum(1 for t in found if pred[t] == tag_truth[t]), "class_total": len(found),
           "missing_tags": sorted(set(tag_truth) - set(pred))}
    line_truth = {l["tag"] for l in truth["lines"]}
    line_pred = {o["text"] for o in result["objects"] if o["class"] == "LINE" and o["text"]}
    out["lines"] = prf(len(line_truth & line_pred), len(line_pred - line_truth), len(line_truth - line_pred))
    out["pages_read"] = [p["read_status"] for p in result["pages"]]
    if "READ" not in out["pages_read"]:
        return out
    with tempfile.TemporaryDirectory(prefix="pid-bench-") as tmp:
        with ProjectStore(Path(tmp) / "b.sqlite") as db:
            eid = db.add_extraction(result, source_pdf_bytes=pdf)
            run = analyze_drawing(db, eid, ocr_engine=ocr_engine if variant == "scanned" else None)
            out["stages"] = {k: v["status"] for k, v in run["stages"].items()}
            from pid_reader.engineering.findings import latest_analysis_ids
            ids = latest_analysis_ids(db, eid)
            valves = db.list_linework_candidates(ids["linework"], kind="BOWTIE_VALVE_GEOMETRY_CANDIDATE", limit=500) if "linework" in ids else []
            cand_boxes = [v["candidate"]["bbox"] for v in valves]
            truth_boxes = [transform_box(v["glyph_bbox"], variant, size) for v in truth["valves"]]
            used, tp = set(), 0
            for tb in truth_boxes:
                for i, cb in enumerate(cand_boxes):
                    if i not in used and centre_in(cb, tb):
                        used.add(i)
                        tp += 1
                        break
            out["valves"] = prf(tp, len(cand_boxes) - len(used), len(truth_boxes) - tp)
            graph = drawing_connectivity(db, eid)
            pred_pairs = set()
            for p in graph["paths"]:
                pairs = frozenset(t for lab in (p["a_label"], p["b_label"]) for t in [lab] if t in tag_truth)
                if len(pairs) == 2:
                    pred_pairs.add(pairs)
            truth_pairs = {frozenset((p["a"], p["b"])) for p in truth["paths"]}
            out["paths"] = prf(len(pred_pairs & truth_pairs), len(pred_pairs - truth_pairs), len(truth_pairs - pred_pairs))
    return out


def merge(items: list[dict], key: str) -> dict:
    tp = sum(i[key]["tp"] for i in items if key in i)
    fp = sum(i[key]["fp"] for i in items if key in i)
    fn = sum(i[key]["fn"] for i in items if key in i)
    return prf(tp, fp, fn)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("corpus")
    ap.add_argument("report")
    ap.add_argument("--split", choices=("dev", "final"), default="dev")
    ap.add_argument("--run-final", action="store_true")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--ocr", default="rapidocr")
    args = ap.parse_args(argv)
    corpus = Path(args.corpus)
    manifest = json.loads((corpus / "manifest.json").read_text(encoding="utf-8"))
    if args.split == "final":
        if not args.run_final:
            ap.error("the final split is reserved; pass --run-final to use it (the use is logged)")
        with (corpus / "final_access.log").open("a", encoding="utf-8") as log:
            log.write(f"{datetime.now(timezone.utc).isoformat()} final split scored with commit-state of {ROOT}\n")
    entries = [d for d in manifest["drawings"] if d["split"] == args.split]
    if args.limit:
        entries = entries[: args.limit]
    per = []
    t0 = time.time()
    for i, e in enumerate(entries, 1):
        try:
            per.append(score_drawing(e, (corpus / e["file"]).read_bytes(), args.ocr))
        except Exception as exc:
            per.append({"file": e["file"], "variant": e["variant"], "split": e["split"],
                        "error": f"{type(exc).__name__}: {str(exc)[:200]}"})
        print(f"[{i}/{len(entries)}] {e['file']} {e['variant']}", flush=True)
    by_variant: dict[str, list[dict]] = defaultdict(list)
    for r in per:
        by_variant[r["variant"]].append(r)
    ok = [r for r in per if "error" not in r]
    summary = {
        "kind": "SYNTHETIC_DEVELOPER_BENCHMARK_NOT_INDEPENDENT", "split": args.split, "drawings": len(per),
        "errors": len(per) - len(ok), "seconds": round(time.time() - t0, 1),
        "overall": {k: merge(ok, k) for k in ("tags", "lines", "valves", "paths")},
        "class_accuracy_of_found_tags": {"correct": sum(r["class_correct"] for r in ok), "total": sum(r["class_total"] for r in ok)},
        "by_variant": {v: {"drawings": len(items), **{k: merge([r for r in items if "error" not in r], k)
                                                       for k in ("tags", "lines", "valves", "paths")}}
                       for v, items in sorted(by_variant.items())},
        "per_drawing": per,
        "not_evaluated": ["instrument-to-equipment signal attachment", "off-page connectors", "flow direction",
                          "real industrial drawings (no independent ground truth exists yet)"],
    }
    Path(args.report).write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print(json.dumps({k: summary[k] for k in ("split", "drawings", "errors", "overall", "class_accuracy_of_found_tags")}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
