"""Write a software bill of materials and third-party notices from the locked Windows environment.

    python tools/make_sbom.py

Reads requirements-lock-win312.txt, asks the installed distributions for their *declared* licence metadata, and writes docs/rev_x/SBOM.json and
docs/rev_x/THIRD_PARTY_NOTICES.md. Declared metadata is not a legal review: items whose licence needs attention (copyleft or bundled binaries) are flagged for the
owner, and nothing here grants or checks redistribution rights. RapidOCR model files are listed separately with their SHA-256 when present.
"""
from __future__ import annotations

import hashlib
import json
import re
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FLAG = {
    "pyside6": "LGPL-3.0 / commercial (Qt for Python): dynamic linking and notices needed; confirm distribution terms",
    "shiboken6": "LGPL-3.0 / commercial (Qt for Python): as PySide6",
    "pyinstaller": "GPL-2.0 with bootloader exception: frozen apps may be distributed; confirm the exception covers your use",
    "pyinstaller-hooks-contrib": "GPL-2.0 / Apache-2.0 hooks: build-time only",
    "opencv-python": "Apache-2.0 wrapper; wheels bundle FFmpeg (LGPL): confirm if redistributing",
    "pymupdf": "AGPL-3.0 / commercial: NOT used; do not add as a default dependency",
    "reportlab": "BSD-3-Clause: used to generate test fixtures",
}


def _app_version() -> str:
    import sys
    sys.path.insert(0, str(ROOT / "src"))
    from pid_reader import __version__
    return __version__


def declared_license(dist) -> str:
    md = dist.metadata
    if md.get("License-Expression"):
        return md["License-Expression"]
    lic = (md.get("License") or "").strip()
    if lic and len(lic) < 80 and "\n" not in lic:
        return lic
    cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    return "; ".join(cls) if cls else (lic[:80] + "..." if lic else "UNDECLARED")


def main() -> int:
    names = []
    for line in (ROOT / "requirements-lock-win312.txt").read_text(encoding="utf-8").splitlines():
        m = re.match(r"([A-Za-z0-9_.\-]+)==([^\s;]+)", line.strip())
        if m:
            names.append((m.group(1), m.group(2)))
    comps = []
    for name, ver in sorted(names, key=lambda t: t[0].lower()):
        try:
            d = metadata.distribution(name)
            lic, installed = declared_license(d), d.version
            home = d.metadata.get("Home-page") or d.metadata.get("Project-URL") or ""
        except metadata.PackageNotFoundError:
            lic, installed, home = "NOT_INSTALLED_HERE", "", ""
        comps.append({"type": "library", "name": name, "version": ver, "installed_version": installed, "declared_license": lic,
                      "attention": FLAG.get(name.lower(), ""), "homepage": home})
    models = []
    try:
        import rapidocr_onnxruntime
        base = Path(rapidocr_onnxruntime.__file__).parent / "models"
        for f in sorted(base.glob("*.onnx")):
            models.append({"file": f.name, "sha256": hashlib.sha256(f.read_bytes()).hexdigest(), "bytes": f.stat().st_size,
                           "source": "bundled in the rapidocr-onnxruntime wheel (PP-OCR family); licence to be confirmed from the wheel (declared Apache-2.0)",
                           "task": "text detection / classification / recognition", "network_at_runtime": False})
    except Exception:
        pass
    sbom = {"bomFormat": "pid-reader-sbom", "specVersion": "1", "application": {"name": "P&ID Reader", "version": _app_version()},
            "components": comps, "models": models,
            "notes": ["Generated from requirements-lock-win312.txt and installed metadata; declared licences are not a legal review.",
                      "No model weight is downloaded at run time; all models ship inside wheels.",
                      "Standards (ISA 5.1, ISO 10628) and vendor symbol catalogues are not bundled; symbols are original geometry."]}
    out = ROOT / "docs" / "rev_x"
    (out / "SBOM.json").write_text(json.dumps(sbom, indent=1), encoding="utf-8")
    lines = ["# Third-party notices", "", "Generated by `tools/make_sbom.py`. Licences are as **declared** by each package's metadata; this is not a legal review, and full licence texts "
             "must be added to any redistributed build. Items marked ATTENTION need an owner/legal decision before distribution.", "",
             "| Package | Version | Declared licence | Attention |", "|---|---|---|---|"]
    for c in comps:
        lines.append(f"| {c['name']} | {c['version']} | {c['declared_license'][:70]} | {c['attention']} |")
    lines += ["", "## Models", ""] + ([f"* `{m['file']}`  sha256 `{m['sha256'][:16]}…`  ({m['bytes']} bytes) - {m['source']}" for m in models] or ["* none found in this environment"])
    lines += ["", "## Not bundled", "", "* ISA 5.1 and ISO 10628 text, vendor/client symbol libraries, public example drawings (`Example P&IDs/` is git-ignored; redistribution licence unknown).",
              "* The official DEXPI 2.0.1 XSD (never downloaded).", ""]
    (out / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"components": len(comps), "models": len(models), "attention": sum(1 for c in comps if c["attention"])}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
